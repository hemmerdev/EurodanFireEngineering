IF OBJECT_ID(N'dbo.CLIENT', N'U') IS NULL
BEGIN
	CREATE TABLE dbo.CLIENT(
		ClientId INT PRIMARY KEY IDENTITY(1,1),
		ContactName NVARCHAR(100) NULL,
		CompanyName NVARCHAR(150) NOT NULL,
		Phone NVARCHAR(30) NULL,
		Email NVARCHAR(254) NULL
	);
END;

IF OBJECT_ID(N'dbo.PROJECT', N'U') IS NULL
BEGIN
	CREATE TABLE dbo.PROJECT(
		ProjectId INT PRIMARY KEY IDENTITY(1,1),
		ProjectNumber NVARCHAR(30) NOT NULL,
			CONSTRAINT UQ_ProjectNumber UNIQUE (ProjectNumber),

		ProjectName NVARCHAR(200) NOT NULL,

		ProjectStatus NVARCHAR(30) NOT NULL
			CONSTRAINT DF_PROJECT_ProjectStatus DEFAULT (N'Pending')
			CONSTRAINT CK_PROJECT_ProjectStatus
				CHECK (ProjectStatus IN (N'Pending', N'Approved')),

		ProjectManager NVARCHAR(100) NULL,
		FeeProposal Decimal(10,2) NULL,

		PbdbStatus VARCHAR(3) NULL
			CONSTRAINT CK_PROJECT_PbdbStatus
				CHECK (PbdbStatus IS NULL OR PbdbStatus IN (N'Yes', N'No', N'N/A')),

		FserStatus VARCHAR(3) NULL
			CONSTRAINT CK_PROJECT_FserStatus
				CHECK (FserStatus IS NULL OR FserStatus IN (N'Yes', N'No', N'N/A')),

		PaymentDueDate DATE NULL,
		OutstandingAmount Decimal(10,2) NULL,
		InvoicedAmount Decimal(10,2) NULL,
		BuildingSurveyor NVARCHAR(100) NULL,
		Comments NVARCHAR(MAX) NULL,
		ClientId INT NOT NULL,
			CONSTRAINT FK_PROJECT_CLIENT 
				FOREIGN KEY (ClientId) REFERENCES dbo.CLIENT(ClientId)
	);
END;


IF OBJECT_ID(N'dbo.BUILDING', N'U') IS NULL
BEGIN
	CREATE TABLE dbo.BUILDING(
		BuildingId INT PRIMARY KEY IDENTITY(1,1),
		Name NVARCHAR(150) NOT NULL,
		Address NVARCHAR(250) NOT NULL,
	);
END;

IF OBJECT_ID(N'dbo.PROJECT_BUILDING', N'U') IS NULL
BEGIN
	CREATE TABLE dbo.PROJECT_BUILDING(
		ProjectId INT NOT NULL,
		BuildingId INT NOT NULL,

		CONSTRAINT PK_PROJECT_BUILDING 
			PRIMARY KEY (ProjectId, BuildingId),

		CONSTRAINT FK_PROJECT_BUILDING_PROJECT 
			FOREIGN KEY (ProjectId) REFERENCES dbo.PROJECT(ProjectId),
		CONSTRAINT FK_PROJECT_BUILDING_BUILDING 
			FOREIGN KEY (BuildingId) REFERENCES dbo.BUILDING(BuildingId)
	);
END;

